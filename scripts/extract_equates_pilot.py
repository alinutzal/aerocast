# CONC3D (concentrations)
# ---------------------------------------------------------------------------

def build_conc_zarr_view(cache_path):
    bucket, key = CONC_BUCKET_KEY
    url = f"s3://{bucket}/{key}"
    if cache_path.exists():
        with open(cache_path) as f:
            refs = json.load(f)
    else:
        t0 = time.time()
        refs = kc3.NetCDF3ToZarr(url, storage_options={"anon": True}, inline_threshold=0).translate()
        cache_path.parent.mkdir(parents=True, exist_ok=True)
        with open(cache_path, "w") as f:
            json.dump(refs, f)
        print(f"  kerchunk header parse: {time.time() - t0:.1f}s", flush=True)
    import fsspec
    fs = fsspec.filesystem("reference", fo=refs, remote_protocol="s3", remote_options={"anon": True})
    return xr.open_dataset(fs.get_mapper(""), engine="zarr", consolidated=False)


def validate_conc_subset(ds, row0, row1, col0, col1, hour_index=12):
    """Read the FULL layer-1 O3 field for one hour directly, and compare against the subset
    read for the same hour/rows/cols. Confirms the byte-range read is correct, not just fast."""
    full = ds["O3"].isel(TSTEP=hour_index, LAY=0).values  # (ROW, COL), full CONUS
    subset = ds["O3"].isel(TSTEP=hour_index, LAY=0, ROW=slice(row0, row1), COL=slice(col0, col1)).values
    expected = full[row0:row1, col0:col1]
    if not np.array_equal(subset, expected):
        raise ValueError("CONC3D subset validation FAILED: subset read does not match full-field read")
    print(f"  validation OK: subset read matches full-field read exactly (hour index {hour_index}, "
          f"{subset.size} cells, O3 range {subset.min():.3f}-{subset.max():.3f} ppbv)")


def extract_conc(cfg, grid_sub, out_dir, cache_dir, limit_days=None):
    print("=== CONC3D extraction ===", flush=True)
    box = cfg["equates"]["box"]
    row0, row1 = box["row0"] - box["ring"], box["row0"] + box["size"] + box["ring"]
    col0, col1 = box["col0"] - box["ring"], box["col0"] + box["size"] + box["ring"]

    ds = build_conc_zarr_view(cache_dir / "conc3d_refs.json")
    validate_conc_subset(ds, row0, row1, col0, col1)

    n_hours = ds.sizes["TSTEP"] - 1  # drop the trailing Aug 1 00Z record
    assert n_hours == 31 * 24, n_hours
    days = july_days(limit=limit_days)
    var_units = {}

    sub = ds[CONC_VARS].isel(TSTEP=slice(0, n_hours), LAY=0,
                              ROW=slice(row0, row1), COL=slice(col0, col1))
    for v in CONC_VARS:
        var_units[v] = str(ds[v].attrs.get("units", "")).strip()

    written = []
    for d, day in enumerate(days):
        out_path = out_dir / f"equates_conc_{str(day).replace('-', '')}.nc"
        if out_path.exists():
            written.append(out_path)
            continue
        t0 = time.time()
        day_slice = sub.isel(TSTEP=slice(d * 24, (d + 1) * 24)).load()
        data = {v: day_slice[v].values[:, None, :, :].astype(np.float32) for v in CONC_VARS}
        write_ioapi_file(out_path, day, grid_sub, var_units, data)
        written.append(out_path)
        print(f"  {day} conc -> {out_path.name} ({time.time() - t0:.1f}s)", flush=True)
    return written, var_units


