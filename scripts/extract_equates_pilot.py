class SubRangeFile(io.RawIOBase):
    """A read-only view of [offset, offset+size) of another seekable, readable file object."""

    def __init__(self, base, offset, size):
        self.base, self.offset, self.size, self.pos = base, offset, size, 0

    def readable(self):
        return True

    def seekable(self):
        return True

    def seek(self, pos, whence=0):
        if whence == 0:
            self.pos = pos
        elif whence == 1:
            self.pos += pos
        elif whence == 2:
            self.pos = self.size + pos
        return self.pos

    def tell(self):
        return self.pos

    def readinto(self, b):
        n = min(len(b), self.size - self.pos)
        if n <= 0:
            return 0
        self.base.seek(self.offset + self.pos)
        data = self.base.read(n)
        b[:len(data)] = data
        self.pos += len(data)
        return len(data)

    def close(self):
        pass  # the tar member's lifetime is shorter than the underlying S3 file's


def open_tar_member(fs, tar_key, member_name):
    """h5netcdf.File for one member of a tar on S3, fetching only that member's bytes
    (plus whatever h5netcdf/h5py reads on top for the variables actually accessed)."""
    base = fs.open(tar_key, "rb")
    tf = tarfile.open(fileobj=base)
    member = None
    for m in tf.getmembers():
        if m.name.endswith(member_name):
            member = m
            break
    if member is None:
        raise FileNotFoundError(f"{member_name} not found in {tar_key}")
    sub = SubRangeFile(base, member.offset_data, member.size)
    return h5netcdf.File(sub, mode="r"), base


def extract_static(fs, grid_sub, row0, row1, col0, col1, out_path):
    if out_path.exists():
        return out_path
    tar_key = MCIP_TAR_TEMPLATE.format(mon=7, date="20190701")
    h5, base = open_tar_member(fs, tar_key, "GRIDCRO2D_20190701.nc4")
    data = {}
    var_units = {}
    for v in STATIC_VARS:
        arr = np.asarray(h5.variables[v][0, 0, row0:row1, col0:col1], dtype=np.float32)
        data[v] = arr[None, None, :, :]
        var_units[v] = str(h5.variables[v].attrs.get("units", "")).strip()
    h5.close()
    base.close()
    write_ioapi_file(out_path, "2019-07-01", grid_sub, var_units, data,
                      extra_attrs={"FILEDESC": "AeroCast EQUATES pilot static fields (GRIDCRO2D subset)"})
    print(f"  static -> {out_path.name}", flush=True)
    return out_path


def extract_met(fs, cfg, grid_sub, out_dir, limit_days=None):
    print("=== MCIP meteorology extraction ===", flush=True)
    box = cfg["equates"]["box"]
    row0, row1 = box["row0"] - box["ring"], box["row0"] + box["size"] + box["ring"]
    col0, col1 = box["col0"] - box["ring"], box["col0"] + box["size"] + box["ring"]

    extract_static(fs, grid_sub, row0, row1, col0, col1, out_dir / "static.nc")

    days = july_days(limit=limit_days)
    written = []
    var_units = {}
    for day in days:
        stamp = str(day).replace("-", "")
        out_path = out_dir / f"equates_meteo_{stamp}.nc"
        if out_path.exists():
            written.append(out_path)
            continue
        t0 = time.time()
        tar_key = MCIP_TAR_TEMPLATE.format(mon=7, date=stamp)
        h5, base = open_tar_member(fs, tar_key, f"METCRO2D_{stamp}.nc4")
        data = {}
        for v in MET_VARS:
            arr = np.asarray(h5.variables[v][0:24, 0, row0:row1, col0:col1], dtype=np.float32)
            data[v] = arr[:, None, :, :]
            var_units[v] = str(h5.variables[v].attrs.get("units", "")).strip()
        h5.close()
        base.close()
        write_ioapi_file(out_path, day, grid_sub, var_units, data)
        written.append(out_path)
        print(f"  {day} meteo -> {out_path.name} ({time.time() - t0:.1f}s)", flush=True)
    return written, var_units


# ---------------------------------------------------------------------------

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--config", required=True)
    ap.add_argument("--only", choices=["conc", "met", "both"], default="both")
    ap.add_argument("--limit-days", type=int, default=None, help="only extract the first N days of July (for testing)")
    args = ap.parse_args()

    cfg = load_config(args.config)
    eq = cfg["equates"]
    box = eq["box"]
    out_dir = Path(eq["extracted_dir"])
    cache_dir = Path(eq["cache_dir"])
    out_dir.mkdir(parents=True, exist_ok=True)
    cache_dir.mkdir(parents=True, exist_ok=True)

    new_xorig, new_yorig = SOURCE_GRID.subgrid_origin(box["row0"] - box["ring"], box["col0"] - box["ring"])
    grid_sub = IoapiGrid(SOURCE_GRID.p_alp, SOURCE_GRID.p_bet, SOURCE_GRID.p_gam,
                          SOURCE_GRID.xcent, SOURCE_GRID.ycent, new_xorig, new_yorig,
                          SOURCE_GRID.xcell, SOURCE_GRID.ycell)

    t_start = time.time()
    if args.only in ("conc", "both"):
        extract_conc(cfg, grid_sub, out_dir, cache_dir, limit_days=args.limit_days)
    if args.only in ("met", "both"):
        fs = s3fs.S3FileSystem(anon=True)
        extract_met(fs, cfg, grid_sub, out_dir, limit_days=args.limit_days)
    print(f"Done in {time.time() - t_start:.1f}s", flush=True)


if __name__ == "__main__":
    main()
