"""Extract a pilot dataset for AeroCast from the EPA EQUATES CMAQ run (July 2019, surface
layer, a 72x72 read area - a 64x64 box plus a 4-cell ring - over central California) from
the public S3 buckets epa-equates-v1 (concentrations) and cmas-equates (meteorology).

Never downloads the source files whole: CONC3D (386 GB, netCDF3) is read through a
kerchunk-generated byte-range index into a lazy zarr/xarray view; MCIP (per-day tars, ~7 GB
each) is read by seeking to the wanted member's byte range (via a seekable s3fs file handle
and Python's tarfile) and then reading just that member's HDF5 chunks with h5netcdf.

Usage: python scripts/extract_equates_pilot.py --config configs/data/equates_2019_07_ca12km.yaml
"""
import argparse
import io
import json
import sys
import time
from pathlib import Path

import h5netcdf
import kerchunk.netCDF3 as kc3
import netCDF4
import numpy as np
import s3fs
import tarfile
import xarray as xr

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))
from aerocast.config import load_config  # noqa: E402
from aerocast.grid_proj import IoapiGrid  # noqa: E402

CONC_BUCKET_KEY = (
    "epa-equates-v1",
    "CMAQ_12US1/OUTPUT/CONC3D/COMBINE_CONC3D_v532_cb6r3_ae7_aq_WR413_MYR_STAGE_2019_12US1_201907.nc",
)
MCIP_TAR_TEMPLATE = (
    "cmas-equates/CMAQ_12US1/INPUT/2019/met/mcip_v51_wrf_v411_noltng/{mon:02d}/"
    "MCIPv51_WRFv411_noltng_12US1.35L.{date}.tar"
)
CONC_VARS = ["NO", "NO2", "O3", "ATOTIJ"]
MET_VARS = ["TEMP2", "WSPD10", "WDIR10", "PBL", "RGRND", "Q2"]
STATIC_VARS = ["LAT", "LON", "HT", "LWMASK"]

SOURCE_GRID = IoapiGrid(
    p_alp=33.0, p_bet=45.0, p_gam=-97.0, xcent=-97.0, ycent=40.0,
    xorig=-2556000.0, yorig=-1728000.0, xcell=12000.0, ycell=12000.0,
)


def july_days(year=2019, limit=None):
    days = [np.datetime64(f"{year}-07-{d:02d}") for d in range(1, 32)]
    return days[:limit] if limit else days


def julian(day):
    day = np.datetime64(day, "D")
    y = day.astype("datetime64[Y]")
    doy = int((day - y) / np.timedelta64(1, "D")) + 1
    year = int(str(y))
    return year * 1000 + doy


# ---------------------------------------------------------------------------
# IOAPI-style NetCDF writer
# ---------------------------------------------------------------------------

def write_ioapi_file(path, day, grid, var_units, data, extra_attrs=None):
    """data: {name: (TSTEP, LAY, ROW, COL) float32}. Writes TFLAG + variables + IOAPI attrs."""
    names = list(data.keys())
    tstep, lay, nrow, ncol = next(iter(data.values())).shape
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_suffix(".tmp.nc")
    with netCDF4.Dataset(tmp, "w", format="NETCDF4_CLASSIC") as ds:
        ds.createDimension("TSTEP", None)
        ds.createDimension("DATE-TIME", 2)
        ds.createDimension("LAY", lay)
        ds.createDimension("VAR", len(names))
        ds.createDimension("ROW", nrow)
        ds.createDimension("COL", ncol)

        sdate = julian(day)
        tflag = ds.createVariable("TFLAG", "i4", ("TSTEP", "VAR", "DATE-TIME"))
        tflag.units = "<YYYYDDD,HHMMSS>"
        tflag_vals = np.zeros((tstep, len(names), 2), dtype=np.int32)
        for t in range(tstep):
            tflag_vals[t, :, 0] = sdate
            tflag_vals[t, :, 1] = t * 10000
        tflag[:] = tflag_vals

        for name in names:
            var = ds.createVariable(name, "f4", ("TSTEP", "LAY", "ROW", "COL"), zlib=True, complevel=4)
            var.units = var_units.get(name, "")
            var.long_name = name
            var[:] = data[name]

        ds.FILEDESC = "AeroCast EQUATES pilot extract"
        ds.GDNAM = "12US1_pilot_ca"
        ds.GDTYP = 2
        ds.P_ALP, ds.P_BET, ds.P_GAM = grid.p_alp, grid.p_bet, grid.p_gam
        ds.XCENT, ds.YCENT = grid.xcent, grid.ycent
        ds.XORIG, ds.YORIG = grid.xorig, grid.yorig
        ds.XCELL, ds.YCELL = grid.xcell, grid.ycell
        ds.NCOLS, ds.NROWS, ds.NLAYS, ds.NVARS = ncol, nrow, lay, len(names)
        ds.SDATE, ds.STIME, ds.TSTEP = sdate, 0, 10000
        setattr(ds, "VAR-LIST", "".join(f"{n:<16s}" for n in names))  # matches the BAAQMD files' attribute name
        for k, v in (extra_attrs or {}).items():
            setattr(ds, k, v)
    tmp.replace(path)
    return path


